create or replace function public.next_bid_amount(b int) returns int
language sql immutable as $$ select case when b < 10 then b+1 when b < 20 then b+2 else b+5 end $$;

create or replace function public.start_player(p_pool_id uuid, p_roll_number text, p_name text)
returns jsonb language plpgsql security definer set search_path=public as $$
declare pid uuid;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  insert into players(pool_id,roll_number,name,status) values(p_pool_id,p_roll_number,p_name,'live') returning id into pid;
  update auction_states set current_player_id=pid,current_bid=3,leader_team_id=null,status='live',updated_at=now() where pool_id=p_pool_id;
  return jsonb_build_object('player_id',pid);
end $$;

create or replace function public.place_bid(p_pool_id uuid, p_team_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare s auction_states%rowtype; next_amount int; remaining int;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  select * into s from auction_states where pool_id=p_pool_id for update;
  if s.current_player_id is null or s.status <> 'live' then raise exception 'No live player'; end if;
  next_amount := public.next_bid_amount(s.current_bid);
  select remaining_ep into remaining from team_pool_balances where pool_id=p_pool_id and team_id=p_team_id for update;
  if remaining is null then raise exception 'Team is not configured for this pool'; end if;
  if remaining < next_amount then raise exception 'Team cannot afford % EP', next_amount; end if;
  if s.leader_team_id = p_team_id then raise exception 'That team already leads'; end if;
  insert into bids(pool_id,player_id,team_id,amount) values(p_pool_id,s.current_player_id,p_team_id,next_amount);
  update auction_states set current_bid=next_amount,leader_team_id=p_team_id,updated_at=now() where pool_id=p_pool_id;
  return jsonb_build_object('amount',next_amount);
end $$;

create or replace function public.sell_current_player(p_pool_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare s auction_states%rowtype;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  select * into s from auction_states where pool_id=p_pool_id for update;
  if s.current_player_id is null or s.leader_team_id is null then raise exception 'Player has no winning team'; end if;
  update team_pool_balances set remaining_ep=remaining_ep-s.current_bid where pool_id=p_pool_id and team_id=s.leader_team_id and remaining_ep>=s.current_bid;
  if not found then raise exception 'Insufficient team balance'; end if;
  update players set status='sold',sold_team_id=s.leader_team_id,sold_price=s.current_bid where id=s.current_player_id;
  insert into auction_results(pool_id,player_id,team_id,final_price,status) values(p_pool_id,s.current_player_id,s.leader_team_id,s.current_bid,'SOLD');
  update auction_states set current_player_id=null,current_bid=3,leader_team_id=null,status='idle',updated_at=now() where pool_id=p_pool_id;
  return jsonb_build_object('sold',true);
end $$;

create or replace function public.mark_unsold(p_pool_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare s auction_states%rowtype;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  select * into s from auction_states where pool_id=p_pool_id for update;
  if s.current_player_id is null then raise exception 'No live player'; end if;
  update players set status='unsold' where id=s.current_player_id;
  insert into auction_results(pool_id,player_id,final_price,status) values(p_pool_id,s.current_player_id,0,'UNSOLD');
  update auction_states set current_player_id=null,current_bid=3,leader_team_id=null,status='idle',updated_at=now() where pool_id=p_pool_id;
  return jsonb_build_object('unsold',true);
end $$;

create or replace function public.relist_player(p_player_id uuid)
returns jsonb language plpgsql security definer set search_path=public as $$
declare p players%rowtype;
begin
  if auth.uid() is null then raise exception 'Admin login required'; end if;
  select * into p from players where id=p_player_id;
  if p.status <> 'unsold' then raise exception 'Only unsold players can be brought back'; end if;
  update players set status='available' where id=p_player_id;
  return jsonb_build_object('player_id',p_player_id,'base_price',3);
end $$;

