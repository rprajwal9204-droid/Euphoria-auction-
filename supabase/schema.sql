-- EUPHORIA AUCTION: Supabase schema + secure auction RPCs
create extension if not exists pgcrypto;

create table if not exists public.teams (
  id uuid primary key default gen_random_uuid(),
  name text unique not null,
  color_key text not null,
  sort_order int not null
);

create table if not exists public.pools (
  id uuid primary key default gen_random_uuid(),
  batch_year int not null check (batch_year between 2021 and 2025),
  gender text not null check (gender in ('Male','Female')),
  unique(batch_year, gender)
);

create table if not exists public.team_pool_balances (
  id bigint generated by default as identity primary key,
  pool_id uuid not null references public.pools(id) on delete cascade,
  team_id uuid not null references public.teams(id) on delete cascade,
  starting_ep int not null default 150 check (starting_ep >= 0),
  remaining_ep int not null default 150 check (remaining_ep >= 0),
  unique(pool_id, team_id)
);

create table if not exists public.players (
  id uuid primary key default gen_random_uuid(),
  pool_id uuid not null references public.pools(id) on delete cascade,
  roll_number text not null,
  name text not null,
  base_price int not null default 3 check (base_price = 3),
  status text not null default 'available' check (status in ('available','live','sold','unsold')),
  sold_team_id uuid references public.teams(id),
  sold_price int,
  created_at timestamptz not null default now()
);

create table if not exists public.auction_states (
  pool_id uuid primary key references public.pools(id) on delete cascade,
  current_player_id uuid references public.players(id),
  current_bid int not null default 3,
  leader_team_id uuid references public.teams(id),
  status text not null default 'idle' check (status in ('idle','live','sold','unsold')),
  updated_at timestamptz not null default now()
);

create table if not exists public.bids (
  id bigint generated by default as identity primary key,
  pool_id uuid not null references public.pools(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  team_id uuid not null references public.teams(id),
  amount int not null check (amount >= 3),
  created_at timestamptz not null default now()
);

create table if not exists public.auction_results (
  id bigint generated by default as identity primary key,
  pool_id uuid not null references public.pools(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete cascade,
  team_id uuid references public.teams(id),
  final_price int not null default 0,
  status text not null check (status in ('SOLD','UNSOLD')),
  created_at timestamptz not null default now()
);

